#!/usr/bin/env python3
"""Fixed, domain-stratified split of the 1,211 official train queries (step 5).

969 queries train the cross-encoder folds and the gate; 242 queries calibrate the
gate threshold. The split is a pure function of the query list and the seed, so it
can be regenerated byte for byte; queries without any dense-top-100 positive are
kept (they are part of the honest base rate, not an error to filter away).
"""
import argparse
import json
from pathlib import Path

DOMAINS = ["bitcoin", "cardano", "economics", "genealogy", "history", "hsm",
           "iota", "law", "monero", "politics", "quant", "travel", "workplace"]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--seed", type=int, default=20261120)
    ap.add_argument("--train-frac", type=float, default=0.8)
    ap.add_argument("--out", default="results/replacement_v2/train_split.json")
    args = ap.parse_args()
    import numpy as np
    rng = np.random.default_rng(args.seed)
    split = {}
    total = 0
    for domain in DOMAINS:
        path = args.root / "data/track1_tempo" / domain / "examples_train.jsonl"
        qids = []
        with path.open(encoding="utf-8") as fh:
            for line in fh:
                item = json.loads(line)
                qids.append(item.get("qid") or item.get("_id") or item.get("id"))
        qids = [q for q in qids if q]
        order = rng.permutation(len(qids))
        cut = int(round(args.train_frac * len(qids)))
        tr = sorted(qids[i] for i in order[:cut])
        ca = sorted(qids[i] for i in order[cut:])
        split[domain] = {"train": tr, "calibration": ca}
        total += len(qids)
    out = {"seed": args.seed, "train_frac": args.train_frac, "n_train_queries": total,
           "n_train": sum(len(v["train"]) for v in split.values()),
           "n_calibration": sum(len(v["calibration"]) for v in split.values()),
           "domains": split,
           "rule": "domain-stratified permutation split of examples_train.jsonl; "
                   "queries are never dropped for lacking a dense-top-100 positive"}
    path = args.root / args.out
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(json.dumps({k: v for k, v in out.items() if k != "domains"}, indent=1))
    for d in DOMAINS:
        print(d, len(split[d]["train"]), len(split[d]["calibration"]))
    print("wrote", path)


if __name__ == "__main__":
    main()
